df = pd.read_csv("/content/framingham.csv")

print(df.isnull().sum())

df=df.dropna()

df.info()

x= df.drop('Risk', axis=1)
y= df['Risk']
print(x)

print(df.isnull().sum())



x_train, x_test, y_train, y_test = train_test_split(x,y, test_size=0.20, random_state=42, stratify=y)
